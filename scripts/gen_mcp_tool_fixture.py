#!/usr/bin/env python3
"""Dump the Python skmemory MCP server's tool list and regenerate the Rust schemas.

Writes two files from the Python package that is importable (use PYTHONPATH to
point at a skmemory checkout):

* tests/fixtures/mcp/python-tools.json: every tool's name, description and
  input schema, plus the server's reader policy table. This is the vendored
  fixture tests/mcp_schema_parity.rs compares the Rust server against.
* src/mcp/schemas.rs: the schemas of the tools the Rust engine serves
  (SERVED below), as JSON text constants.

Usage:
    PYTHONPATH=<skmemory checkout> python scripts/gen_mcp_tool_fixture.py

Reads no store and starts no server.
"""

from __future__ import annotations

import asyncio
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Keep in step with SERVED in src/mcp.rs (a test checks the two agree).
SERVED = [
    "memory_store",
    "memory_search",
    "memory_recall",
    "memory_history",
    "memory_list",
    "memory_remind",
    "memory_intentions",
    "memory_intention_done",
]


def main() -> None:
    from skmemory import mcp_server as m

    tools = asyncio.run(m.list_tools())
    fixture = {
        "source": "skmemory/mcp_server.py list_tools() and TOOL_READER_POLICY",
        "tools": [
            {"name": t.name, "description": t.description, "inputSchema": t.inputSchema}
            for t in tools
        ],
        "reader_policy": {
            name: {"class": cls, "note": note} for name, (cls, note) in m.TOOL_READER_POLICY.items()
        },
        "reader_tools": sorted(m._READER_TOOLS),
    }
    dest = ROOT / "tests/fixtures/mcp/python-tools.json"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(json.dumps(fixture, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {dest} ({len(tools)} tools)")

    by_name = {t["name"]: t for t in fixture["tools"]}
    lines = [
        "//! GENERATED by scripts/gen_mcp_tool_fixture.py from the Python MCP server. Do not edit.",
        "//!",
        "//! One JSON text per served tool: `{name, description, inputSchema}`.",
        "",
        "pub const SCHEMAS: &[(&str, &str)] = &[",
    ]
    for name in SERVED:
        text = json.dumps(by_name[name], indent=2, ensure_ascii=False)
        assert '"#' not in text
        lines.append(f'    (\n        "{name}",\n        r#"{text}"#,\n    ),')
    lines.append("];")
    out = ROOT / "src/mcp/schemas.rs"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
