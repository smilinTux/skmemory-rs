#!/usr/bin/env python3
"""Generate the Python `str.isprintable` table (SKMEM-R-07).

Usage: python tests/golden/gen_printable.py

Writes `src/printable_table.rs`: every code point `str.isprintable` rejects
(except none: ASCII space is printable), as sorted inclusive ranges. The tick's
alert text cleaner needs it to match Python's `_clean` exactly. Rust has no
general-category lookup in std, so the table is generated, never hand-edited.
"""
import sys
import unicodedata
from pathlib import Path

root = Path(__file__).resolve().parents[2]
ranges = []
start = prev = None
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    if not chr(cp).isprintable():
        if start is None:
            start = prev = cp
        elif cp == prev + 1:
            prev = cp
        else:
            ranges.append((start, prev))
            start = prev = cp
if start is not None:
    ranges.append((start, prev))

lines = [
    "// @generated by tests/golden/gen_printable.py; do not edit by hand.",
    f"// Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}: code points `str.isprintable` rejects.",
    f"pub(crate) static NONPRINTABLE: [(u32, u32); {len(ranges)}] = [",
]
lines += [f"    (0x{a:X}, 0x{b:X})," for a, b in ranges]
lines.append("];")
(root / "src" / "printable_table.rs").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(len(ranges), "ranges")
