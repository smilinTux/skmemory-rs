#!/usr/bin/env python3
"""Generate the Python `\\w` table and tokenisation goldens (SKMEM-R-04).

Usage: python tests/golden/gen_word_chars.py

Writes `src/wordchars_table.rs` (every code point `re` treats as `\\w`, as
sorted inclusive ranges) and `tests/golden/word_chars.json` (inputs with the
tokens `re.findall(r"\\w+", s)` returns). Rust's `char::is_alphanumeric` is
NOT `\\w`: it counts Other_Alphabetic (combining marks, circled letters), which
Python's `str.isalnum` does not. Regenerate with this script, never by hand.
"""
import json
import re
import sys
import unicodedata
from pathlib import Path

root = Path(__file__).resolve().parents[2]
w = re.compile(r"\w", re.UNICODE)
ranges = []
start = prev = None
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    if w.match(chr(cp)):
        if start is None:
            start = prev = cp
        elif cp == prev + 1:
            prev = cp
        else:
            ranges.append((start, prev))
            start = prev = cp
if start is not None:
    ranges.append((start, prev))

lines = [
    "// @generated by tests/golden/gen_word_chars.py; do not edit by hand.",
    f"// Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}: code points matched by re `\\w`.",
    f"pub(crate) static WORD_RANGES: [(u32, u32); {len(ranges)}] = [",
]
lines += [f"    (0x{a:X}, 0x{b:X})," for a, b in ranges]
lines.append("];")
(root / "src" / "wordchars_table.rs").write_text("\n".join(lines) + "\n", encoding="utf-8")

samples = [
    "plain words here",
    "snake_case and CamelCase",
    "café au lait",  # e + combining acute (Mn)
    "naïve",
    "नमस्ते",  # Devanagari with vowel signs (Mc/Mn)
    "Ⓐⓐ circled",  # circled letters (So, Other_Alphabetic)
    "x² y³ z½",  # superscripts, vulgar fraction (No)
    "ⅠⅡ roman",  # roman numerals (Nl)
    "١٢٣ arabic-indic digits",
    "一二三 〇",  # CJK ideographs, ideographic zero
    "กิ่ง thai marks",
    "eͅ greek ypogegrammeni",
    "a‍b zwj",
    "a­b soft hyphen",
    "tab\tsplit\nnew",
    "emoji \U0001f600 ok",
    "ᴬʰ modifier letters",
    "̀́ lone marks",
    "prb-6f069c5e",
    "aཀཱིb tibetan",
    "\U0001d7ce\U0001d7cf math digits",
    "ﬁ ligature K kelvin",
]
(root / "tests" / "golden" / "word_chars.json").write_text(
    json.dumps(
        [{"input": s, "tokens": re.findall(r"\w+", s)} for s in samples],
        indent=1,
        ensure_ascii=True,
    )
    + "\n",
    encoding="utf-8",
)
print(len(ranges), "ranges")
